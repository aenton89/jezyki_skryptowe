function Pieces.new(type_idx)
    return {
        type = type_idx,
        rot = 1,
        -- kolumna i potem wiersz startowy (0-based offset)
        x = 3,
        y = 0,
    }
end

function Pieces.get_matrix(piece)
    return Pieces.DEFS[piece.type].rots[piece.rot]
end

function Pieces.get_color(piece)
    return Pieces.DEFS[piece.type].color
end

function Pieces.rot_count(piece)
    return #Pieces.DEFS[piece.type].rots
end



